'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const Campaign = require('../src/prototype/engine.js');
const { audio } = require('./helpers/audio-context.cjs');
const app = fs.readFileSync(path.resolve(__dirname, '../src/prototype/app.js'), 'utf8');
assert(app.includes('if (!started && !sceneTransition && !startupUpdatePending && !titleLoading)'));
assert(app.includes('audio.update(game, !focused || document.hidden || recovering'));
assert(app.includes('const entryUnlock = audio.unlock()'));
assert(app.includes('return audio.productionPending || true'));
assert(app.includes('if (!entryAudioAttempted && audio.ctx)'), 'no audio device must not delay Continue');
const a = audio();
a.enableProduction();
a.ambient = () => {};
a.transitionScore = () => {};
a.sceneDetails = () => {};
a.updateEnvironment = () => {};
a.setStemGain = () => {};
let starts = 0;
a.setRecordedScore = async (spec) => {
  starts++;
  a.recordedScore = { id: spec.id, voices: [{}, {}] };
  return true;
};
(async () => {
  const campaign = new Campaign('normal', 'paladin', () => .43);
  a.update(campaign, false, { started: false });
  await a.productionPending;
  assert.equal(a.recordedScore.id, 'title');
  assert.equal(a.mixScene, 'title');
  a.update(campaign, false, { started: true });
  await a.productionPending;
  const selected = a.recordedScore.id;
  assert(selected.startsWith('place-') || selected.startsWith('settlement-'));
  const before = starts;
  a.update(campaign, false, { started: true, menu: true });
  assert.equal(a.recordedScore.id, selected);
  assert.equal(a.mixScene, 'world');
  assert.equal(starts, before, 'menu cannot restart the current score');
  a.update(campaign, false, { started: true, paused: true });
  assert.equal(a.ctx.state, 'running');
  assert.equal(a.recordedScore.id, selected);
  a.update(campaign, false, { started: false, menu: true });
  await a.productionPending;
  assert.equal(a.recordedScore.id, 'title');
  assert.equal(a.mixScene, 'title');
  console.log('PASS title -> location -> in-game menu/pause -> title music');
})().catch((e) => { console.error(e); process.exitCode = 1; });
