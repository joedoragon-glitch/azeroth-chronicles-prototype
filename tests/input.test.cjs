assert.equal(controls.actionFor('KeyF'),'confirm');
// Floating geometry is independent of the movement engine and other tap owners.
const v=Input.floatingJoystickVector;
assert.deepEqual(v({x:55,y:300},{x:55,y:300},42),{x:0,y:0},'stationary thumb does not move');
assert.deepEqual(v({x:55,y:300},{x:60,y:303},42),{x:0,y:0},'minor tremor stays in deadzone');
assert(Math.abs(v({x:55,y:300},{x:97,y:300},42).x-1)<1e-9,'full displacement reaches native x=1');
assert(Math.abs(v({x:55,y:300},{x:155,y:300},42).x-1)<1e-9,'vector remains bounded');
assert(Math.hypot(...Object.values(v({x:20,y:20},{x:100,y:100},42)))<=1.00001);
const zone=Input.floatingJoystickZone;
assert(zone({x:60,y:340},{width:800,height:375}),'landscape lower-left is eligible');
assert(!zone({x:210,y:340},{width:800,height:375}),'right-side gameplay taps remain world taps');
assert(!zone({x:60,y:170},{width:800,height:375}),'upper-left world taps remain world taps');
assert(!zone({x:60,y:340},{width:800,height:375},[{x:40,y:310,width:50,height:50}]),'interact hitbox owns gesture');
assert(zone({x:55,y:740},{width:375,height:800}),'portrait lower-left remains eligible');
controls.select('joystickMode','invalid');assert.equal(controls.preferences.joystickMode,'fixed','invalid selection falls back safely');
controls.select('joystickMode','floating');assert.equal(controls.preferences.joystickMode,'floating');
// Previous device preferences preserve the former numeric bindings and custom layouts.
