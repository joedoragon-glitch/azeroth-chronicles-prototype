assert(controls.rebind('skill1','KeyE').includes('already used'),'E is reserved for targeting');
assert.equal(controls.rebind('target','KeyY'),null);
assert.equal(controls.rebind('skill1','KeyR'),null);
assert.equal(controls.actionFor('KeyR'),'skill1','retired menu keys are rebindable');
controls.select('phoneLayout','left-hand');controls.select('touchMove',false);controls.select('mouseMove',true);
controls.select('joystickMode','floating');
controls=Input.create(storage);
assert.equal(controls.actionFor('ArrowUp'),'up');
assert.equal(controls.actionFor('KeyR'),'skill1');
assert.equal(controls.preferences.preset,'custom','custom key settings persist');
assert.equal(controls.preferences.phoneLayout,'left-hand');
assert.equal(controls.preferences.joystickMode,'floating','independent preference survives reload');
assert.equal(controls.preferences.touchMove,false);
assert.equal(controls.preferences.mouseMove,true);
assert.equal(controls.applyPreset('invalid'),false);
assert.equal(controls.applyPreset('classic'),true);
assert.equal(controls.preferences.preset,'classic');
assert.equal(controls.actionFor('Digit1'),'skill1');
assert.equal(controls.actionFor('ShiftLeft'),'skill7');
assert.equal(controls.actionFor('KeyB'),'skill8');
assert.equal(controls.actionFor('KeyI'),null,'even Classic does not restore inventory hotkeys');
assert.equal(controls.actionFor('KeyJ'),null,'even Classic does not restore journal hotkeys');
assert.equal(controls.actionFor('KeyR'),null,'retired inventory alias does not apply');
assert.equal(controls.actionFor('KeyT'),null,'retired journal alias does not apply');
assert.equal(controls.applyPreset('left'),true);
