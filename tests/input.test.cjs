assert.equal(controls.preferences.mouseMove, false);
assert.equal(controls.preferences.preset,'right','new devices default to two-handed WASD + right-hand skills');
for(const [i,code] of ['KeyJ','KeyK','KeyL','KeyU','KeyI','Space','KeyO','KeyN'].entries())
  assert.equal(controls.actionFor(code),'skill'+(i+1),'new skill '+(i+1)+' default');
assert.equal(controls.actionFor('KeyW'),'up');
assert.equal(controls.actionFor('KeyE'),'target','E cycles hero targets by default');
