 up:'KeyI',down:'KeyK',left:'KeyJ',right:'KeyL',
 skill1:'KeyD',skill2:'KeyS',skill3:'KeyA',skill4:'KeyE',
 skill5:'KeyW',skill6:'Space',skill7:'KeyQ',skill8:'KeyR',target:'KeyO',
