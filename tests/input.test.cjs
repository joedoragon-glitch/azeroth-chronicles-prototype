assert.equal(controls.actionFor('KeyT'),null,'T no longer opens the quest journal');
for(const [name,bindings] of Object.entries(Input.presets)){
  assert.equal(new Set(Object.values(bindings)).size,controls.actions.length,
    name+' has one unique key per action');
  assert(controls.actions.every(([id])=>bindings[id]),name+' covers every gameplay action');
}
assert(controls.rebind('up','KeyS').includes('already used'));
assert(controls.rebind('up','Escape'));
