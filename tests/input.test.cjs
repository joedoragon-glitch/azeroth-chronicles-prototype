assert.equal(controls.actionFor('KeyZ'),'map');
assert.equal(controls.actionFor('KeyM'),'map');
assert(!controls.actions.some(([id])=>['inventory','quests','interact'].includes(id)),
  'Inventory and quest journal are available via menus, not keyboard bindings');
